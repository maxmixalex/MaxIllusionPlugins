    /// <summary>
    /// Small, dependency-free rules shared by the plugin and the headless
    /// tests. Keep game-specific actions in the Harmony integration classes.
    /// </summary>
    internal static class FemboyRules
    {
        // Original Koikatsu h_particle TextAsset: LiquidSiru (particle ID 0)
        // is attached to this transform, not to the Kokan base bone.
        internal const string DefaultMaleFinishBone = "cm_J_dan109_00";
        // Conservative model-local launch defaults. The old 2.5 m/s and
        // world-up 18-degree tilt overshot in the RX18 SoS test.
        internal const float DefaultFluidLaunchSpeed = 0.85f;
        internal const float DefaultFluidLocalPitch = 0f;


        /// <summary>
        /// The base game's aibulayer_02 order is:
        /// 0 hand, 1 finger, 2 tongue, 3 denma vibrator (IDs 5/6),
        /// 4 p_item_vibe phallus-shaped toy (IDs 7/8).
        /// This removes the LAST item, not the massager before it.
        /// </summary>
        internal static bool IsPhallusToyLayer(int icon, int leftItemId, int rightItemId)
        {
            return icon == 25 && leftItemId == 7 && rightItemId == 8;
        }

        // Native MetaballShoot emits its first droplet immediately and
        // then uses one aInterval entry for each additional droplet.
        // A multiplier of 2 therefore doubles (intervals + 1), not just
        // the number of wait times. Clamped to avoid excessive physics load.
        internal static int FluidIntervalCount(int nativeIntervals, float amount)
        {
            if (float.IsNaN(amount) || float.IsInfinity(amount))
                amount = 1f;
            if (amount < 0.25f) amount = 0.25f;
            if (amount > 5f) amount = 5f;
            int baseShots = nativeIntervals < 1 ? 2 : nativeIntervals + 1;
            int shots = (int)Math.Ceiling(baseShots * amount);
            if (shots < 2) shots = 2;
            if (shots > 80) shots = 80;
            return shots - 1;
        }

        internal static bool NeedsNewFluidPreset(int existingMode,
            int existingPose, int nextMode, int nextPose)
        {
            return existingMode != nextMode || existingPose != nextPose;
        }

        // Pitch is a rotation in the bone's anatomical local frame,
        // not an angle above a fixed world-space horizontal plane.
        internal static float SafeLocalFluidPitch(float degrees)
        {
            if (float.IsNaN(degrees) || float.IsInfinity(degrees))
                return DefaultFluidLocalPitch;
            if (degrees < -30f) return -30f;
            if (degrees > 30f) return 30f;
            return degrees;
        }

        /// <summary>
        /// Native HSonyu voice IDs for the climax Start transition. These
        /// are generated by HSonyu even when shared HFlag.finish has already
        /// been cleared by another mod or a subsequent state. The variant
        /// starting at 363 is the +38 female-initiative layout.
        /// </summary>
        internal static bool IsSonyuClimaxStartVoice(int code)
        {
            return (code >= 325 && code <= 330) ||
                   (code >= 363 && code <= 368);
        }

        // 318/319 (and +38 female initiative) can signal a combined
        // heroine/male finish. Only accept them when HFlag.finish is sameW
        // or sameS and the animation is in a finish Start/Loop state.
        internal static bool IsSonyuCombinedClimaxVoice(int code)
        {
            return code == 318 || code == 319 || code == 356 || code == 357;
        }

        internal static bool ShouldEmitFromConsumedCombinedVoice(int before, int after)
        {
            return IsSonyuCombinedClimaxVoice(before) && before != after;
        }

        // HVoiceCtrl.VoiceProc can defer a voice for many Update frames.
        // Avoid fluid emission until the original method has actually
        // consumed its pending climax cue.
        internal static bool ShouldEmitFromConsumedSonyuVoice(
            int codeBefore, int codeAfter)
        {
            return IsSonyuClimaxStartVoice(codeBefore) &&
                   codeAfter != codeBefore;
        }

        // A finish Start/Loop/A is part of the *same* Sonyu orgasm, even
        // when native voice codes 325 and 327 are both consumed.
        internal static bool IsSonyuFinishPhase(string state)
        {
            if (string.IsNullOrEmpty(state)) return false;
            return state.IndexOf("WF_IN_", StringComparison.Ordinal) >= 0 ||
                   state.IndexOf("WS_IN_", StringComparison.Ordinal) >= 0 ||
                   state.IndexOf("SF_IN_", StringComparison.Ordinal) >= 0 ||
                   state.IndexOf("SS_IN_", StringComparison.Ordinal) >= 0 ||
                   state.IndexOf("WF_OUT_", StringComparison.Ordinal) >= 0 ||
                   state.IndexOf("WS_OUT_", StringComparison.Ordinal) >= 0 ||
                   state.IndexOf("SF_OUT_", StringComparison.Ordinal) >= 0 ||
                   state.IndexOf("SS_OUT_", StringComparison.Ordinal) >= 0;
        }

        // Unlike *_WF/WS/SF/SS_IN_Loop, the ordinary *_M_IN_Loop
        // represents a new insertion cycle. Do not arm again in *_IN_A.
        internal static bool IsSonyuFluidEmissionPhase(string state)
        {
            return IsSonyuFinishPhase(state) &&
                !IsSonyuFinishRecovery(state) &&
                (state.EndsWith("_Start", StringComparison.Ordinal) ||
                 state.EndsWith("_Loop", StringComparison.Ordinal));
        }

        internal static bool IsSonyuFinishRecovery(string state)
        {
            if (!IsSonyuFinishPhase(state)) return false;
            return state.EndsWith("_A", StringComparison.Ordinal);
        }

        // HCtrl's "before simultaneous climax" state is A_OLoop. It
        // separates two finish requests without updating native orgasm
        // counters; firing while here would be premature.
        internal static bool IsSonyuPreCombinedFinish(string state)
        {
            return !string.IsNullOrEmpty(state) &&
                (state == "OLoop" ||
                 state.EndsWith("_OLoop", StringComparison.Ordinal) ||
                 state == "OStart" ||
                 state.EndsWith("_OStart", StringComparison.Ordinal));
        }

        internal static bool IsSonyuOrdinaryMotionLoop(string state)
        {
            if (string.IsNullOrEmpty(state) || IsSonyuFinishPhase(state))
                return false;
            return state.EndsWith("_M_IN_Loop", StringComparison.Ordinal) ||
                   state.EndsWith("_M_OUT_Loop", StringComparison.Ordinal);
        }

        internal static bool IsReversedHoushiName(string name)
        {
            return !string.IsNullOrEmpty(name) &&
                (name.StartsWith("[Reversed] ", StringComparison.Ordinal) ||
                 name.StartsWith("[反转] ", StringComparison.Ordinal));
        }

        // Koikatsu Houshi body clips have the S/M/L or SM/ML motion
        // variants. Never exchange actor facial, reaction, or Sonyu clips.
        internal static bool IsHoushiBodyMotionClip(string name)
        {
            if (string.IsNullOrEmpty(name)) return false;
            bool variant = name.StartsWith("S_", StringComparison.Ordinal) ||
                name.StartsWith("M_", StringComparison.Ordinal) ||
                name.StartsWith("L_", StringComparison.Ordinal) ||
                name.StartsWith("SM_", StringComparison.Ordinal) ||
                name.StartsWith("ML_", StringComparison.Ordinal);
            return variant &&
                (name.IndexOf("_IN_", StringComparison.Ordinal) > 0 ||
                 name.IndexOf("_OUT_", StringComparison.Ordinal) > 0) &&
                (name.EndsWith("_Start", StringComparison.Ordinal) ||
                 name.EndsWith("_Loop", StringComparison.Ordinal) ||
                 name.EndsWith("_A", StringComparison.Ordinal));
        }

        internal static bool IsFemaleInsertionFinishStart(string state)
        {
            if (string.IsNullOrEmpty(state)) return false;
            return state.EndsWith("WF_IN_Start", StringComparison.Ordinal) ||
                   state.EndsWith("WS_IN_Start", StringComparison.Ordinal) ||
                   state.EndsWith("SF_IN_Start", StringComparison.Ordinal) ||
                   state.EndsWith("SS_IN_Start", StringComparison.Ordinal);
        }

        internal static float SafeShaftFraction(float value)
        {
            if (float.IsNaN(value) || float.IsInfinity(value))
                return 0.50f;
            if (value < 0f) return 0f;
            if (value > 1f) return 1f;
            return value;
        }

        internal static bool CanSwapFullController(bool enabled, bool explicitOptIn)
        {
            return enabled && explicitOptIn;
        }

        /// <summary>
        /// Sonyu Start has two pages of seven actions, selected by
        /// HSceneProc.AnimationListInfo.isFemaleInitiative.
        /// </summary>
        internal static int FrontInsertStartIndex(bool femaleInitiative)
        {
            return femaleInitiative ? 7 : 0;
        }

        internal static bool HasBothFrontButtons(int buttonCount, int startIndex)
        {
            return startIndex >= 0 && buttonCount >= startIndex + 2;
        }

        internal static float SafeBoneScale(float value)
        {
            if (float.IsNaN(value) || float.IsInfinity(value))
                return 1f;
            if (value < 0.5f) return 0.5f;
            if (value > 2f) return 2f;
            return value;
        }

        /// <summary>
        /// Resolve a requested bone against actual installed rig names.
        /// Example: cm_j_dan100 -> cm_J_dan100_00 (observed in RX18).
        /// Rank: 0 exact, 1 case-insensitive, 2 exact base + _00,
        /// 3 exact base + other numeric suffix, -1 incompatible.
        /// Avoid loose prefix matching (100 must not match 101).
        /// </summary>
        internal static int BoneMatchRank(string requested, string actual)
        {
            if (string.IsNullOrEmpty(requested) || string.IsNullOrEmpty(actual))
                return -1;

            if (string.Equals(requested, actual, StringComparison.Ordinal))
                return 0;
            if (string.Equals(requested, actual, StringComparison.OrdinalIgnoreCase))
                return 1;

            if (actual.Length <= requested.Length + 1 ||
                !actual.StartsWith(requested, StringComparison.OrdinalIgnoreCase) ||
                actual[requested.Length] != '_')
                return -1;

            string suffix = actual.Substring(requested.Length + 1);
            for (int i = 0; i < suffix.Length; i++)
                if (suffix[i] < '0' || suffix[i] > '9')
                    return -1;

            return suffix == "00" ? 2 : 3;
        }

        /// <summary>
        /// The original HVoiceCtrl loads the two heroine voice tables, not a
        /// separate male voice channel. These codes designate the female
        /// climax-specific line choices in the Aibu and Sonyu state machines.
        /// 142/143 = Aibu climax/start recovery; 318/319 and 325..330 =
        /// Sonyu female climax/combined-finish voice selections.
        /// Never suppress male-only inside/outside cue indices (320..324).
        /// </summary>
        internal static bool IsFemaleClimaxVoice(int mode, int voiceCode)
        {
            if (mode == 0)
                return voiceCode == 142 || voiceCode == 143;
            if (mode == 2)
            {
                // Female-initiative poses use a +38 offset in HSonyu.Proc
                // (Game.isAdd20 && nowAnimationInfo.isFemaleInitiative).
                // The previous filter silently missed those scenes.
                int code = voiceCode;
                if ((code >= 356 && code <= 357) ||
                    (code >= 363 && code <= 368))
                    code -= 38;
                return code == 318 || code == 319 ||
                    (code >= 325 && code <= 330);
            }
            return false;
        }

        /// <summary>
        /// A Sonyu climax affecting the heroine uses finish kinds orgW,
        /// sameW, orgS, sameS. Inside/outside-only belong to the actual
        /// male participant and must never retarget the heroine.
        /// </summary>
        internal static bool IsFemaleFinishAnimation(int mode, int finishKind, string state)
        {
            if (mode != 2 || finishKind < 3 || finishKind > 6 ||
                string.IsNullOrEmpty(state))
                return false;

            if (state.StartsWith("A_", StringComparison.Ordinal))
                state = state.Substring(2);

            return state == "OLoop" ||
                   state.StartsWith("WF_", StringComparison.Ordinal) ||
                   state.StartsWith("SF_", StringComparison.Ordinal) ||
                   state.StartsWith("WS_", StringComparison.Ordinal) ||
                   state.StartsWith("SS_", StringComparison.Ordinal);
        }

        /// <summary>
        /// Native male appendage rig group. Keep the pose follower scoped to
        /// these bones: the partner's whole-body motion is not copied.
        /// </summary>
        internal static string MaleSegmentBoneName(int index)
        {
            return index < 100 || index > 109
                ? null : "cm_J_dan" + index.ToString() + "_00";
        }

        /// <summary>
        /// Deduplicate particle FX for the currently active heroine, not
        /// for the shared HFlag instance alone.
        /// </summary>
        internal static long EffectKey(int flagInstanceId, int heroineIndex)
        {
            return ((long)flagInstanceId << 2) | (uint)(heroineIndex & 3);
        }
    }

    /// <summary>
    /// Stateful, per-heroine/per-scene Sonyu orgasm gate. The native game
    /// signals one finish through HFlag, SetPlay, and several voice codes;
    /// a short cooldown alone mistakes late recovery cues for new orgasms.
    /// </summary>
    internal sealed class FemboySonyuCycleGate
    {
        private int pose = int.MinValue;
        private bool fired;
        private bool sawFinishPhase;
        private bool sawRecovery;
        private bool sawPreCombined;
        private string previousState;
        private int cycle;
        private int nativeOrgasmSignals;
        private int signalsAtLastEmission;

        // HFlag.AddSonyuOrg/AddSonyuAnalOrg are game-owned orgasm counters.
        // Record them as cycle evidence, NEVER emit here: those counters can
        // advance while the preceding recovery A state is still active.
        internal void NoteNativeOrgasm(int poseId, string state)
        {
            Observe(poseId, state);
            nativeOrgasmSignals++;
        }

        internal bool CanFire(int poseId, string state)
        {
            return CanFire(poseId, state, float.PositiveInfinity);
        }

        internal bool CanFire(int poseId, string state, float secondsSinceLastShot)
        {
            Observe(poseId, state);
            // Native counters identify a new simultaneous/combined climax
            // even when SS/WS/SF transitions skip the usual recovery state.
            // A short refractory interval blocks duplicate hooks for a single
            // native event; the state must still be an emission phase.
            if (fired && nativeOrgasmSignals > signalsAtLastEmission &&
                FemboyRules.IsSonyuFluidEmissionPhase(state) &&
                secondsSinceLastShot >= 0.9f)
            {
                fired = false;
                sawRecovery = false;
                sawFinishPhase = false;
                cycle++;
            }
            return !fired;
        }

        internal void MarkFired(int poseId, string state)
        {
            Observe(poseId, state);
            fired = true;
            signalsAtLastEmission = nativeOrgasmSignals;
            if (FemboyRules.IsSonyuFinishPhase(state)) sawFinishPhase = true;
        }

        internal void Observe(int poseId, string state)
        {
            if (pose != poseId)
            {
                pose = poseId;
                fired = false;
                sawFinishPhase = false;
                sawRecovery = false;
                sawPreCombined = false;
                previousState = null;
                cycle = 0;
                nativeOrgasmSignals = 0;
                signalsAtLastEmission = 0;
            }

            // RX18 can transition directly from the climax recovery A
            // into the next climax Start, without ever evaluating *_M_IN_Loop.
            // An observed recovery -> *new* start edge is therefore just as
            // authoritative as returning to ordinary insertion movement.
            bool newFinishStart = FemboyRules.IsFemaleInsertionFinishStart(state) &&
                !string.Equals(previousState, state, StringComparison.Ordinal);
            bool followingRecovery = fired && sawRecovery && newFinishStart;
            bool followingHCtrlPre = fired && sawPreCombined && newFinishStart;
            if (fired && (sawFinishPhase || sawPreCombined) &&
                (FemboyRules.IsSonyuOrdinaryMotionLoop(state) ||
                 followingRecovery || followingHCtrlPre))
            {
                fired = false;
                sawFinishPhase = false;
                sawRecovery = false;
                sawPreCombined = false;
                cycle++;
            }
            if (fired && FemboyRules.IsSonyuPreCombinedFinish(state))
                sawPreCombined = true;
            if (FemboyRules.IsSonyuFinishPhase(state))
                sawFinishPhase = true;
            if (FemboyRules.IsSonyuFinishRecovery(state))
                sawRecovery = true;
            previousState = state;
        }

        internal string DiagnosticState
        {
            get { return "pose=" + pose + " fired=" + fired +
                " sawFinish=" + sawFinishPhase +
                " sawRecovery=" + sawRecovery +
                " sawHCtrlPre=" + sawPreCombined + " cycle=" + cycle +
                " nativeOrg=" + nativeOrgasmSignals +
                " shotOrg=" + signalsAtLastEmission; }
        }
    }
